import fs from 'node:fs'
import path from 'node:path'
import { type Coordinates, drawWindow, type ImageLike } from '@shared/draw'
import type { WindowMessage } from '@shared/messages'
import { createRasterContext, decodePng, type RasterImage } from './raster'

export interface ScreenshotOptions {
  /** When set, the PNG is also written to this file path. */
  path?: string
}

export interface ScreenshotRenderer {
  /**
   * Renders a window to a PNG with the same drawing code and assets as the web
   * canvas. Resolves with the image; `options.path` also writes it to a file.
   */
  screenshot(window: WindowMessage, options?: ScreenshotOptions): Promise<Buffer>
}

const BACKGROUND_SOURCE = /^windows\/(.+)\.png$/

export function createScreenshotRenderer(assetsDir: string): ScreenshotRenderer {
  const windowsDir = path.join(assetsDir, 'windows')
  const backgrounds = new Map<string, RasterImage>()
  const textures = new Map<string, RasterImage>()
  let coordinates: Coordinates | null = null

  function readAsset(file: string): Buffer {
    try {
      return fs.readFileSync(file)
    } catch (error) {
      throw new Error(
        `(mineflayer-web-inventory) Unable to read "${file}" — the client assets ` +
          'must be built (run "npm run build")',
        { cause: error },
      )
    }
  }

  function loadCoordinates(): Coordinates {
    if (coordinates) return coordinates
    // The file is generated by the client build; the cast documents the parse boundary.
    coordinates = JSON.parse(
      readAsset(path.join(windowsDir, 'coordinates.json')).toString(),
    ) as Coordinates
    return coordinates
  }

  function loadBackground(type: string): RasterImage {
    const cached = backgrounds.get(type)
    if (cached) return cached

    const image = decodePng(readAsset(path.join(windowsDir, `${type}.png`)))
    backgrounds.set(type, image)
    return image
  }

  function loadDataUrl(source: string): RasterImage {
    const cached = textures.get(source)
    if (cached) return cached

    const comma = source.indexOf(',')
    if (comma < 0 || !source.slice(0, comma).endsWith(';base64')) {
      throw new Error(
        `(mineflayer-web-inventory) Unsupported image source "${source.slice(0, 32)}"`,
      )
    }
    const image = decodePng(Buffer.from(source.slice(comma + 1), 'base64'))
    textures.set(source, image)
    return image
  }

  async function loadImage(source: string): Promise<ImageLike> {
    const background = BACKGROUND_SOURCE.exec(source)
    if (background) return loadBackground(background[1] ?? '')
    if (source.startsWith('data:')) return loadDataUrl(source)
    throw new Error(`(mineflayer-web-inventory) Unsupported image source "${source}"`)
  }

  return {
    async screenshot(window, options = {}) {
      const context = createRasterContext()
      await drawWindow(context, window, { coordinates: loadCoordinates(), loadImage })
      const buffer = context.toPng()
      if (options.path) await fs.promises.writeFile(options.path, buffer)
      return buffer
    },
  }
}
